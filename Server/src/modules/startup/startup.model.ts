import { Schema, model } from 'mongoose';
import { IStartup } from './startup.types';

const startupDocumentCategoryEnum = [
  'business_plan',
  'incorporation_certificate',
  'moa',
  'aoa',
  'llp_agreement',
  'partnership_deed',
  'founder_agreement',
  'company_pan',
  'tan_allotment',
  'gst_registration',
  'registered_office_proof',
  'office_noc_or_utility_bill',
  'startup_india_certificate',
  'trademark_certificate',
  'patent_proof',
  'bank_account_proof',
  'regulatory_license',
  'prototype_documentation',
  'technical_documentation',
  'drawings_diagrams',
  'design_plan_sketch',
  'prior_art_search',
  'dpiit_certificate',
  'udyam_certificate',
  'government_certificate_other',
  'dpr',
  'itr_filing',
  'revenue_proof',
  'grant_certificate',
  'award_certificate',
  'funding_proof',
] as const;

const startupSchema = new Schema<IStartup>(
  {
    founderIds: { type: [Schema.Types.ObjectId], required: true, default: [], index: true },
    teamMemberIds: { type: [Schema.Types.ObjectId], default: [] },
    projectId: { type: Schema.Types.ObjectId, default: undefined },
    name: { type: String, required: true, trim: true, default: '' },
    tagline: { type: String, required: true, trim: true, default: '' },
    category: { type: String, required: true, trim: true, default: '' },
    stage: {
      type: String,
      enum: ['Pre-Idea', 'Ideation', 'MVP', 'Pre-Launch', 'Launched'],
      default: 'Pre-Idea',
    },
    phase: {
      type: String,
      enum: ['creation', 'building', 'launched'],
      default: 'creation',
    },
    pitchDeckUrl: { type: String, default: undefined },
    pitchDeckName: { type: String, default: undefined },
    pitchDeckStorageProvider: { type: String, enum: ['cloudinary', 's3'], default: undefined },
    pitchDeckStorageKey: { type: String, default: undefined },
    pitchDeckCloudinaryPublicId: { type: String, default: undefined },
    teamSize: { type: Number, default: 1 },
    teamMemberTypes: {
      type: Map,
      of: { type: String, enum: ['founder', 'coFounder', 'mentor', 'advisor'] },
      default: {},
    },
    fundingNeeded: { type: Number, default: undefined },
    activeProducts: { type: Number, default: 1 },
    businessProfile: {
      problemStatement: { type: String, trim: true, default: '' },
      solutionSummary: { type: String, trim: true, default: '' },
      targetCustomers: { type: String, trim: true, default: '' },
      marketAnalysis: { type: String, trim: true, default: '' },
      revenueModel: { type: String, trim: true, default: '' },
      goToMarketPlan: { type: String, trim: true, default: '' },
    },
    registrationProfile: {
      problemStatement: { type: String, trim: true, default: '' },
      solutionDifferentiation: { type: String, trim: true, default: '' },
      coreInnovation: { type: String, trim: true, default: '' },
      priorArtStatus: { type: String, trim: true, default: '' },
      workingMechanism: { type: String, trim: true, default: '' },
      keyComponents: { type: String, trim: true, default: '' },
      developmentStage: {
        type: String,
        enum: ['idea', 'prototype', 'mvp', 'market_ready'],
        default: 'idea',
      },
      documentationReadiness: { type: String, trim: true, default: '' },
      inventorOwnership: {
        type: String,
        enum: ['individual', 'team', 'organization'],
        default: 'individual',
      },
      developmentContext: { type: String, trim: true, default: '' },
      targetMarkets: { type: String, trim: true, default: '' },
      commercializationStrategy: {
        type: String,
        enum: ['build_startup', 'license', 'sell', 'partnership'],
        default: 'build_startup',
      },
      publicDisclosureStatus: { type: String, trim: true, default: '' },
      legalAgreements: { type: String, trim: true, default: '' },
      ipProtectionType: {
        type: String,
        enum: ['patent', 'copyright', 'trademark', 'design'],
        default: 'patent',
      },
    },
    initializationProfile: {
      vision: { type: String, trim: true, default: '' },
      mission: { type: String, trim: true, default: '' },
      foundingStory: { type: String, trim: true, default: '' },
      teamComposition: { type: String, trim: true, default: '' },
      productStage: {
        type: String,
        enum: ['idea', 'prototype', 'mvp', 'market_ready'],
        default: 'idea',
      },
      productOverview: { type: String, trim: true, default: '' },
      customerProfile: { type: String, trim: true, default: '' },
      marketOpportunity: { type: String, trim: true, default: '' },
      businessModel: {
        type: String,
        enum: [
          'subscription',
          'transactional',
          'marketplace',
          'freemium',
          'advertising',
          'services',
          'hardware',
          'hybrid',
        ],
        default: 'subscription',
      },
      pricingStrategy: { type: String, trim: true, default: '' },
      competitiveLandscape: { type: String, trim: true, default: '' },
      defensibleMoat: { type: String, trim: true, default: '' },
      currentTraction: { type: String, trim: true, default: '' },
      upcomingMilestones: { type: String, trim: true, default: '' },
      fundingAsk: { type: String, trim: true, default: '' },
      legalEntityType: {
        type: String,
        enum: [
          'not_registered',
          'sole_proprietorship',
          'partnership',
          'llp',
          'private_limited',
          'opc',
        ],
        default: 'not_registered',
      },
      risksAndMitigation: { type: String, trim: true, default: '' },
    },
    innovationProfile: {
      rubricVersion: {
        type: String,
        enum: ['startup_innovation_1000'],
        default: undefined,
      },
      companyProfile: {
        legalStructure: {
          type: String,
          enum: [
            'not_registered',
            'sole_proprietorship',
            'partnership',
            'llp',
            'private_limited',
            'opc',
          ],
          default: 'not_registered',
        },
        cinNumber: { type: String, trim: true, default: '' },
        dpiitRecognitionNumber: { type: String, trim: true, default: '' },
        msmeUdyamNumber: { type: String, trim: true, default: '' },
        otherGovernmentCertificationName: { type: String, trim: true, default: '' },
        otherGovernmentCertificationNumber: { type: String, trim: true, default: '' },
        websiteUrl: { type: String, trim: true, default: '' },
        productDemoUrl: { type: String, trim: true, default: '' },
        portfolioUrl: { type: String, trim: true, default: '' },
      },
      tractionProfile: {
        startupStage: {
          type: String,
          enum: ['idea', 'mvp_ready', 'market_ready', 'revenue_generating'],
          default: 'idea',
        },
        problemClarity: { type: String, trim: true, default: '' },
        uniqueSolution: { type: String, trim: true, default: '' },
        marketDifferentiation: { type: String, trim: true, default: '' },
        patentStatus: {
          type: String,
          enum: ['none', 'filed', 'published'],
          default: 'none',
        },
        hasItrFiling: { type: Boolean, default: false },
        hasRevenueProof: { type: Boolean, default: false },
        hasGovernmentGrant: { type: Boolean, default: false },
        hasAwardRecognition: { type: Boolean, default: false },
        fundingStatus: {
          type: String,
          enum: ['none', 'bootstrapped', 'angel_seed', 'vc'],
          default: 'none',
        },
        activeUsersCustomers: { type: Number, default: 0, min: 0 },
        monthlyGrowthRate: { type: Number, default: 0, min: 0 },
        retentionRate: { type: Number, default: 0, min: 0, max: 100 },
      },
    },
    documents: {
      type: [
        new Schema(
          {
            category: { type: String, enum: startupDocumentCategoryEnum, required: true },
            fileUrl: { type: String, required: true },
            fileType: { type: String, enum: ['pdf', 'image'], required: true },
            fileName: { type: String, required: true },
            fileSizeBytes: { type: Number, required: true },
            uploadedAt: { type: Date, default: () => new Date() },
            uploadedBy: { type: Schema.Types.ObjectId, required: true },
            note: { type: String, trim: true, default: undefined },
            storageProvider: { type: String, enum: ['cloudinary', 's3'], default: undefined },
            storageKey: { type: String, default: undefined },
            cloudinaryPublicId: { type: String, default: undefined },
          },
          { _id: true },
        ),
      ],
      default: [],
    },
    launchedToInvestors: { type: Boolean, default: false },
    launchedToMentors: { type: Boolean, default: false },
    launchedToRecruiters: { type: Boolean, default: false },
    launchedAt: { type: Date, default: undefined },
    marketplaceTermsAcceptedAt: { type: Date, default: undefined },
    marketplaceTermsAcceptedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    marketplaceTermsVersion: { type: String, default: undefined },
    launchFormLocked: { type: Boolean, default: false },
    launchFormLockedAt: { type: Date, default: undefined },
    launchFormUnlockedByAdmin: { type: Boolean, default: false },
    launchFormUnlockedAt: { type: Date, default: undefined },
    launchFormUnlockedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    launchFormUnlockReason: { type: String, default: undefined },
    innovationScoreAtLaunch: { type: Number, default: 0 },
    totalShares: { type: Number, default: 1000, min: 1 },
    availableShares: { type: Number, default: 1000, min: 0 },
    reservedForSole: { type: Number, default: 510, min: 0 },
    maxPennyInvestors: { type: Number, default: 50, min: 1 },
    currentPennyCount: { type: Number, default: 0, min: 0 },
    hasSoleInvestor: { type: Boolean, default: false },
    soleInvestorId: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    traction: {
      patentFiled: { type: Boolean, default: false },
      mvpBuilt: { type: Boolean, default: false },
      revenueGenerating: { type: Boolean, default: false },
      usersCount: { type: Number, default: undefined },
      patentType: { type: String, enum: ['self_filed', 'promove_assisted'], default: undefined },
      patentApplicationId: { type: String, default: undefined },
    },
    reviewStatus: {
      type: String,
      enum: ['draft', 'review_requested', 'changes_requested', 'approved'],
      default: 'draft',
    },
    reviewRequestedAt: { type: Date, default: undefined },
    adminReviewedAt: { type: Date, default: undefined },
    adminReviewedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    adminNotes: { type: String, default: undefined },
    adminEditUnlockActive: { type: Boolean, default: false },
    adminEditUnlockApprovedAt: { type: Date, default: undefined },
    adminEditUnlockApprovedBy: { type: Schema.Types.ObjectId, ref: 'User', default: null },
    adminEditUnlockReason: { type: String, default: undefined },
    fundingGoal: { type: Number, default: undefined, min: 0 },
    currentFunding: { type: Number, default: 0, min: 0 },
    availableEquity: { type: Number, default: 100, min: 0, max: 100 },
    investorCount: { type: Number, default: 0, min: 0 },
    interestedInvestorCount: { type: Number, default: 0, min: 0 },
    trendingScore: { type: Number, default: 0 },
    fundingStatus: {
      type: String,
      enum: ['open', 'partial', 'fully_funded', 'closed'],
      default: 'open',
    },
    lastFundingUpdate: { type: Date, default: undefined },
    pitchRequests: {
      type: [
        new Schema(
          {
            investorId: { type: Schema.Types.ObjectId, ref: 'User', required: true },
            status: {
              type: String,
              enum: ['pending', 'accepted', 'rejected', 'withdrawn'],
              default: 'pending',
            },
            requestedAt: { type: Date, default: () => new Date() },
            respondedAt: { type: Date, default: undefined },
            responseNote: { type: String, trim: true, default: undefined },
          },
          { _id: true },
        ),
      ],
      default: [],
    },
    isActive: { type: Boolean, default: true },
  },
  { timestamps: true },
);

startupSchema.index({ teamMemberIds: 1 });
startupSchema.index({ launchedToInvestors: 1, innovationScoreAtLaunch: -1 });
startupSchema.index({ launchedToMentors: 1 });
startupSchema.index({ launchedToRecruiters: 1 });
startupSchema.index({ reviewStatus: 1, updatedAt: -1 });
startupSchema.index({ fundingStatus: 1, trendingScore: -1 });
startupSchema.index({ launchedToInvestors: 1, trendingScore: -1 });

export const Startup = model<IStartup>('Startup', startupSchema);
